// Run with PLAYWRIGHT_MODULE pointing to an installed Playwright entrypoint.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
import assert from 'node:assert/strict';
const browser = await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
const context = await browser.newContext({viewport:{width:412,height:915},isMobile:true,hasTouch:true,serviceWorkers:'block'});
await context.grantPermissions(['clipboard-read','clipboard-write']);
await context.addInitScript(() => {
 localStorage.setItem('lumeo:auth-session',JSON.stringify({accessToken:'local-test-only',refreshToken:'',expiresAt:null,user:{id:'google-ux-test',email:'test@example.com'}}));
});
await context.route('**/api/**', route => route.fulfill({json:route.request().url().endsWith('/me')?{license:{status:'active'}}:{status:'authorized'},headers:{'access-control-allow-origin':'*'}}));
const page = await context.newPage(); const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{ if(message.type()==='error') errors.push(message.text()); });
await page.goto('http://127.0.0.1:5173/import');
await page.evaluate(async()=>{
 const {IndexedDbService}=await import('/src/services/IndexedDbService.ts');
 const db=new IndexedDbService('lumeo-library-google-ux-test');
 await db.request('genres','readwrite',s=>s.put({id:'test-genre',name:'Geral',color:'#ddd',createdAt:new Date().toISOString()}));
});
await page.goto('http://127.0.0.1:5173/import');
await page.locator('.import-sources').waitFor();
assert.equal(await page.locator('.import-sources button').count(),2);
assert.equal(await page.getByText('Por link',{exact:true}).count(),0);
await page.locator('.import-sources').getByRole('button',{name:/Google Drive/}).click();
const dialog=page.getByRole('dialog',{name:'Google Drive'}); await dialog.waitFor();
await dialog.getByLabel('Nome da biblioteca',{exact:true}).fill('Napoleon Hill');
const link=dialog.getByLabel('Link da pasta do Google Drive',{exact:true});
await link.fill('https://drive.google.com/file/d/invalid/view');
await dialog.getByRole('button',{name:'Salvar',exact:true}).click();
await dialog.getByText('Insira um link válido de uma pasta do Google Drive.').waitFor();
await link.fill('');
await page.evaluate(()=>navigator.clipboard.writeText('https://drive.google.com/drive/folders/Napoleon123'));
await link.focus(); await page.keyboard.press('Control+V');
assert.equal(await link.inputValue(),'https://drive.google.com/drive/folders/Napoleon123');
await dialog.getByRole('button',{name:'Salvar',exact:true}).click();
await dialog.getByRole('button',{name:'Napoleon Hill',exact:true}).waitFor();
assert.equal(await dialog.locator('input').count(),0);
await dialog.getByRole('button',{name:'Adicionar outra biblioteca'}).click();
await dialog.getByLabel('Nome da biblioteca',{exact:true}).fill('Mangás');
await dialog.getByLabel('Link da pasta do Google Drive',{exact:true}).fill('https://drive.google.com/drive/folders/Manga123');
await dialog.getByRole('button',{name:'Salvar',exact:true}).click();
await dialog.getByRole('button',{name:'Mangás',exact:true}).waitFor();
await page.screenshot({path:process.env.GOOGLE_UX_SCREENSHOT ?? '/tmp/lumeo-google-sources.png'});
await dialog.getByRole('button',{name:'Fechar',exact:true}).click();
await page.reload(); await page.locator('.import-sources').getByRole('button',{name:/Google Drive/}).click();
await dialog.getByRole('button',{name:'Mangás',exact:true}).waitFor();
await dialog.getByRole('button',{name:'Napoleon Hill',exact:true}).click();
await dialog.getByText('Google Drive ainda não está configurado.').waitFor();
const name=dialog.getByRole('button',{name:'Napoleon Hill',exact:true});
await name.dispatchEvent('pointerdown',{button:0,clientX:80,clientY:150,pointerType:'touch'});
await page.waitForTimeout(600);
await name.dispatchEvent('pointerup',{button:0});
await dialog.getByRole('button',{name:'Renomear',exact:true}).click();
await dialog.getByLabel('Nome da biblioteca',{exact:true}).fill('Napoleon atualizado');
await dialog.getByRole('button',{name:'Salvar',exact:true}).click();
await dialog.getByRole('button',{name:'Napoleon atualizado',exact:true}).waitFor();
await dialog.getByRole('button',{name:'Mangás',exact:true}).dispatchEvent('contextmenu');
await dialog.getByRole('button',{name:'Alterar link',exact:true}).click();
await dialog.getByLabel('Link da pasta do Google Drive',{exact:true}).fill('https://drive.google.com/drive/folders/NewManga');
await dialog.getByRole('button',{name:'Salvar',exact:true}).click();
await dialog.getByRole('button',{name:'Mangás',exact:true}).dispatchEvent('contextmenu');
page.once('dialog',d=>d.accept());
await dialog.getByRole('button',{name:'Excluir',exact:true}).click();
await page.waitForTimeout(200);
assert.equal(await dialog.getByRole('button',{name:'Mangás',exact:true}).count(),0);
assert.equal(await dialog.getByRole('button',{name:'Napoleon atualizado',exact:true}).count(),1);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:'/tmp/lumeo-google-final.png'});
assert.deepEqual(errors,[]);
console.log(JSON.stringify({viewport:'412x915',sources:2,create:true,invalidLink:true,reload:true,longPress:true,editLink:true,delete:true,unconfiguredError:true,pageErrors:errors}));
await browser.close();
